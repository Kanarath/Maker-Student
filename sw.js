// Service worker de Maker Student: red primero y caché de respaldo, para que funcione sin conexión
// en lo que ya hayas visitado. Sustituye al de la versión anterior (mismo archivo, misma ruta):
// al activarse borra las cachés antiguas «tallerinv-».
const CACHE = "maker-v2";

self.addEventListener("install", () => self.skipWaiting());

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    fetch(req, { cache: "no-cache" })
      .then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
        return res;
      })
      .catch(() => caches.match(req).then((hit) => hit ?? caches.match("/Maker-Student/"))),
  );
});
